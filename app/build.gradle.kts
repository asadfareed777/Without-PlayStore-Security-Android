// =====================================================================
// XOR secret encoder (pure Gradle/Kotlin — no external tools needed)
//
// Reads  : <root>/secrets.properties  (falls back to secrets.demo.properties)
// Writes : app/src/main/cpp/generated/obfuscated_secrets.h
//
// Runs automatically before the native (CMake) build. Gradle's up-to-date
// check means it only re-runs — and only rotates the random key — when the
// secrets file or the JNI names change. Force a new key with:
//     ./gradlew :app:encodeSecrets --rerun-tasks
//
// Encoding per byte i:
//     enc[i] = plain[i] ^ KEY[(i + salt) % KEY_LEN] ^ ((i * 31 + salt) & 0xFF)
// (must match app/src/main/cpp/xor_decoder.h)
// =====================================================================
abstract class EncodeSecretsTask : DefaultTask() {

    @get:InputFile
    abstract val secretsFile: RegularFileProperty

    /** Non-secret strings the native code needs; encoded too so the .so has no readable JNI names. */
    @get:Input
    abstract val jniStrings: MapProperty<String, String>

    @get:OutputFile
    abstract val outputHeader: RegularFileProperty

    @TaskAction
    fun encode() {
        val props = Properties().apply {
            secretsFile.get().asFile.reader(Charsets.UTF_8).use { load(it) }
        }
        val required = listOf("BASE_URL", "IV", "SECRET")
        val missing = required.filter { props.getProperty(it).isNullOrBlank() }
        if (missing.isNotEmpty()) {
            throw GradleException("Missing keys in ${secretsFile.get().asFile.name}: $missing")
        }
        val iv = props.getProperty("IV").trim()
        val secret = props.getProperty("SECRET").trim()
        if (iv.toByteArray().size != 16) logger.warn("WARNING: IV should be exactly 16 bytes for AES/CBC")
        if (secret.toByteArray().size !in setOf(16, 24, 32)) logger.warn("WARNING: SECRET should be 16/24/32 bytes for AES")

        val values = linkedMapOf<String, String>()
        required.forEach { values[it] = props.getProperty(it).trim() }
        values.putAll(jniStrings.get())

        val rnd = SecureRandom()
        val keyLen = 32
        val key = ByteArray(keyLen).also { rnd.nextBytes(it) }

        fun hex(bytes: ByteArray): String = bytes.toList().chunked(12).joinToString(",\n    ", "    ") { row ->
            row.joinToString(", ") { String.format("0x%02X", it.toInt() and 0xFF) }
        }

        val sb = StringBuilder()
        sb.appendLine("// =====================================================================")
        sb.appendLine("// AUTO-GENERATED by the :app:encodeSecrets Gradle task — DO NOT EDIT")
        sb.appendLine("// Contains only XOR-encoded bytes.")
        sb.appendLine("// =====================================================================")
        sb.appendLine("#pragma once")
        sb.appendLine("#include <cstdint>")
        sb.appendLine("#include <cstddef>")
        sb.appendLine()
        sb.appendLine("namespace obf {")
        sb.appendLine()
        sb.appendLine("constexpr size_t KEY_LEN = $keyLen;")
        sb.appendLine("static const uint8_t KEY[KEY_LEN] = {")
        sb.appendLine(hex(key))
        sb.appendLine("};")
        sb.appendLine()

        for ((name, value) in values) {
            val plain = value.toByteArray(Charsets.UTF_8)
            val salt = rnd.nextInt(256)
            val enc = ByteArray(plain.size) { i ->
                (plain[i].toInt() xor key[(i + salt) % keyLen].toInt() xor ((i * 31 + salt) and 0xFF)).toByte()
            }
            sb.appendLine("// $name (${plain.size} bytes)")
            sb.appendLine("static const uint8_t $name[] = {")
            sb.appendLine(hex(enc))
            sb.appendLine("};")
            sb.appendLine("constexpr size_t ${name}_LEN = ${plain.size};")
            sb.appendLine(String.format("constexpr uint8_t %s_SALT = 0x%02X;", name, salt))
            sb.appendLine()
        }
        sb.appendLine("}  // namespace obf")

        val out = outputHeader.get().asFile
        out.parentFile.mkdirs()
        out.writeText(sb.toString().replace("\r\n", "\n"), Charsets.UTF_8)
        logger.lifecycle("encodeSecrets: wrote ${out.name} (${values.size} XOR-encoded strings) from ${secretsFile.get().asFile.name}")
    }
}

val encodeSecrets = tasks.register<EncodeSecretsTask>("encodeSecrets") {
    group = "secure keys"
    description = "XOR-encode secrets into app/src/main/cpp/generated/obfuscated_secrets.h"

    val real = rootProject.file("secrets.properties")
    secretsFile.set(if (real.exists()) real else rootProject.file("secrets.demo.properties"))

    jniStrings.set(
        mapOf(
            "JNI_CLASS" to "com/demo/securekeys/NativeKeys",
            "JNI_M_BASE_URL" to "nativeBaseUrl",
            "JNI_M_IV" to "nativeIv",
            "JNI_M_SECRET" to "nativeSecret",
            "JNI_SIG_STRING" to "()Ljava/lang/String;",
        )
    )
    outputHeader.set(layout.projectDirectory.file("src/main/cpp/generated/obfuscated_secrets.h"))
}

// Make sure the header exists/is current before CMake configures or compiles.
tasks.named("preBuild") { dependsOn(encodeSecrets) }
tasks.matching { it.name.startsWith("configureCMake") || it.name.startsWith("buildCMake") }
    .configureEach { dependsOn(encodeSecrets) }
